import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);

const EXPECTED_VERSIONS = {
  'roughjs': '4.6.6',
  'hachure-fill': '0.5.2',
  'path-data-parser': '0.1.0',
  'points-on-curve': '0.2.0',
  'points-on-path': '0.2.1',
};
for (const [name, version] of Object.entries(EXPECTED_VERSIONS)) {
  const actual = require(`${name}/package.json`).version;
  if (actual !== version) {
    throw new Error(`${name}: expected ${version}, found ${actual}; run \`npm ci\``);
  }
}

// ---------------------------------------------------------------------------
// Instrumentation
//
// rough.js' Random.next() is the only caller of Math.imul, so wrapping it
// counts the seeded random numbers a drawable consumes. Math.random is used by
// rough.js when seed is 0, by the dots filler and as a hachure fallback; it is
// replaced by a deterministic Park-Miller sequence (FALLBACK_SEED) that the
// MoonBit tests inject as `fallback_random`.
// ---------------------------------------------------------------------------

export const FALLBACK_SEED = 1234567;
const realImul = Math.imul;
let seededCalls = 0;
let fallbackCalls = 0;
let fallbackState = FALLBACK_SEED;

Math.imul = function imul(a, b) {
  seededCalls++;
  return realImul(a, b);
};
Math.random = function random() {
  fallbackCalls++;
  fallbackState = realImul(48271, fallbackState);
  return ((2 ** 31 - 1) & fallbackState) / 2 ** 31;
};

/** Resets the counters and the Math.random sequence before each case. */
export function resetRandom() {
  seededCalls = 0;
  fallbackCalls = 0;
  fallbackState = FALLBACK_SEED;
}

export function randomCounts() {
  return { seeded: seededCalls, fallback: fallbackCalls };
}

// ---------------------------------------------------------------------------
// Encoding
// ---------------------------------------------------------------------------

const f64 = new Float64Array(1);
const u64 = new BigUint64Array(f64.buffer);

/** IEEE-754 bit pattern of `x` as 16 lowercase hex digits. */
export function hex(x) {
  if (typeof x !== 'number') throw new Error(`not a number: ${x}`);
  f64[0] = x;
  return u64[0].toString(16).padStart(16, '0');
}

export function hexList(xs) {
  return xs.map(hex).join(' ');
}

/** A MoonBit string literal. */
export function mbtString(s) {
  return JSON.stringify(s).replace(/\\u([0-9a-fA-F]{4})/g, '\\u{$1}');
}

/** Longest string literal written; the compiler limits text segment width. */
const CHUNK = 2000;

/**
 * Writes `src/<pkg>/<file>` containing `let <name> : Array[String] = [...]`
 * for each entry of `arrays`. Long entries are written as a concatenation of
 * literals of at most CHUNK characters.
 */
export function writeFixture(pkg, file, arrays) {
  const lines = [
    '// Code generated by scripts/gen_fixtures.mjs from roughjs 4.6.6. DO NOT EDIT.',
    '',
  ];
  for (const [name, items] of Object.entries(arrays)) {
    lines.push('///|');
    lines.push(`let ${name} : Array[String] = [`);
    for (const item of items) {
      const pieces = [];
      for (let i = 0; i === 0 || i < item.length; i += CHUNK) {
        pieces.push(mbtString(item.slice(i, i + CHUNK)));
      }
      lines.push(`  ${pieces.join(' +\n    ')},`);
    }
    lines.push(']');
    lines.push('');
  }
  const target = path.join(ROOT, 'src', pkg, file);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, lines.join('\n'));
  const count = Object.values(arrays).reduce((n, a) => n + a.length, 0);
  console.log(`wrote src/${pkg}/${file} (${count} entries)`);
}

