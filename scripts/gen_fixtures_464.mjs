// Generates the fixtures of the `roughjs_464` option from rough.js 4.6.4, the
// version @excalidraw/excalidraw depends on. The entry format is the one
// src/core/fixture_runner_test.mbt reads (see `drawableCase` in gen_fixtures.mjs).
//
//   cd scripts && npm ci && node gen_fixtures_464.mjs

import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const version = require('roughjs464/package.json').version;
if (version !== '4.6.4') throw new Error(`expected roughjs 4.6.4, found ${version}`);

const realImul = Math.imul;
let seeded = 0;
let fallback = 0;
let state = 1234567;
Math.imul = (a, b) => {
  seeded++;
  return realImul(a, b);
};
Math.random = () => {
  fallback++;
  state = realImul(48271, state);
  return ((2 ** 31 - 1) & state) / 2 ** 31;
};

const rough = require('roughjs464/bundled/rough.cjs.js');

const f64 = new Float64Array(1);
const u64 = new BigUint64Array(f64.buffer);
function hex(x) {
  if (Number.isNaN(x)) return '7ff8000000000000';
  f64[0] = x;
  return u64[0].toString(16).padStart(16, '0');
}

function encodeOptions(o) {
  const parts = Object.entries(o).map(([k, v]) => {
    if (typeof v === 'number') return k === 'seed' ? `${k}:i:${v}` : `${k}:n:${hex(v)}`;
    return `${k}:s:${v}`;
  });
  return [...parts, 'roughjs464:b:1'].join(';');
}

const code = { path: 'P', fillPath: 'F', fillSketch: 'S' };
const opCode = { move: 'm', lineTo: 'l', bcurveTo: 'c' };

function entry(shape, args, o) {
  seeded = 0;
  fallback = 0;
  state = 1234567;
  const generator = rough.generator();
  const argHex = args.flat(2).map(hex).join(' ');
  // hachure-fill rotates the points it is given in place, so every call gets a copy.
  const d = generator[shape](...structuredClone(args), { ...o });
  const sets = d.sets
    .map((s) => `${code[s.type]}:${s.ops.map((op) => `${opCode[op.op]} ${op.data.map(hex).join(' ')}`).join(',')}`)
    .join(';');
  const argHex = args.flat(2).map(hex).join(' ');
  return [shape, argHex, encodeOptions(o), '-', 'ok', d.shape, sets, seeded, fallback].join('|');
}

const entries = [];
const three = [[0, 0], [80, 40], [2, 3]];
const four = [[0, 0], [90, 5], [70, 80], [3, 2]];
for (const fillStyle of ['hachure', 'cross-hatch', 'zigzag']) {
  for (const seed of [314, 2718]) {
    const o = { seed, fill: 'red', fillStyle };
    // A hachure gap that 4.6.6 would round.
    entries.push(entry('rectangle', [3, 4, 137, 83], { ...o, hachureGap: 5.2, fillWeight: 0.65 }));
    entries.push(entry('ellipse', [50, 40, 100, 80], { ...o, hachureGap: 2.6, curveFitting: 1 }));
    entries.push(entry('polygon', [four], { ...o, hachureGap: 7.4 }));
    // 3 points: 4.6.4 feeds them to curveToBezier directly.
    entries.push(entry('curve', [three], { ...o, hachureGap: 8 }));
    entries.push(entry('curve', [four], { ...o, hachureGap: 8 }));
    // 2 points: 4.6.4 draws no fill at all.
    entries.push(entry('curve', [[[0, 0], [90, 40]]], { ...o, hachureGap: 8 }));
  }
}
for (const seed of [314, 2718]) {
  entries.push(entry('curve', [[[0, 0], [90, 40]]], { seed, fill: 'red', fillStyle: 'solid' }));
  entries.push(entry('curve', [three], { seed, fill: 'red', fillStyle: 'solid' }));
  // 1 point: `_curve` gets 2 points, the branch that differs in 4.6.6.
  entries.push(entry('curve', [[[5, 7]]], { seed }));
}

const CHUNK = 2000;
const lit = (s) => JSON.stringify(s);
const lines = ['// Code generated by scripts/gen_fixtures_464.mjs from roughjs 4.6.4. DO NOT EDIT.', '', '///|', 'let roughjs_464_fixtures : Array[String] = ['];
for (const e of entries) {
  const pieces = [];
  for (let i = 0; i < e.length; i += CHUNK) pieces.push(lit(e.slice(i, i + CHUNK)));
  lines.push(`  ${pieces.join(' +\n    ')},`);
}
lines.push(']', '');
fs.writeFileSync(path.join(ROOT, 'src/core/core_464_fixtures_test.mbt'), lines.join('\n'));
console.log(`wrote src/core/core_464_fixtures_test.mbt (${entries.length} entries)`);
